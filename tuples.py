#NESTED LISTS & TUPLES
#tuple version
tuple1 = (1,2,3,4,5)
tuple2 = ("a","b","c","d") 
tuple3 = (1,"dinosaur",90.8,"perfume",82)

tuple=(12,13,14,15,16,tuple1,17,18,19)

print(tuple1,tuple2,tuple3,tuple)

#list version
list1 = [1,2,3,4,5]
list2 = ["a","b","c","d"]
list3 = [1,"dinosaur",90.8,"perfume",82]

list=[12,13,14,15,16,list1,17,18,19]

print[list1,list2,list3,list]